export const LOCALES = { en: 'en-GB', az: 'az-Latn-AZ', ru: 'ru-RU' };
let lang = 'en';
try {
  const saved = localStorage.getItem('ecoline.lang');
  if (saved && STRINGS[saved]) lang = saved;
  else {
    const nav = (navigator.language || 'en').slice(0, 2);
    if (STRINGS[nav]) lang = nav;
  }
} catch (e) { /* storage unavailable */ }

export function getLang() { return lang; }
export function setLang(l) {
  if (!STRINGS[l]) return;
  lang = l;
  try { localStorage.setItem('ecoline.lang', l); } catch (e) { /* ignore */ }
  document.documentElement.lang = l;
}
export function t(key, params = {}) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}
export function num(x, digits = 1) {
  return new Intl.NumberFormat(LOCALES[lang], { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(x);
}
